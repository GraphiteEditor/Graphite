use crate::{MigrationError, Payload};

/// How stored history survives a format step.
///
/// Under `Rewrite`, [`FormatMigration::migrate_delta`] transforms each record's payload, and the load path then rehashes the
/// `Rev`s and remaps parent links and session cursors. A rewrite is a pure function of content and `Rev`s are content-addressed,
/// so peers applying the same step converge on identical history without coordination.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum HistoryPolicy {
	/// The shape change does not affect stored deltas.
	Untouched,
	/// Each history record is rewritten via `migrate_delta`.
	Rewrite,
	/// No faithful rewrite exists; the document becomes a state-only snapshot.
	Truncate,
}

/// One whole-document format step, migrating version `migrates_from()` to `migrates_from() + 1`.
///
/// Usually generated by `format_migration!` over the frozen types of `migration-formats`. Steps only transform payload
/// content, never identity fields (`id`, `parent`), which the load path recomputes.
pub trait FormatMigration: Send + Sync {
	/// The format version this step upgrades from.
	fn migrates_from(&self) -> u32;
	/// Transform the serialized registry payload.
	fn migrate_registry(&self, registry: &Payload) -> Result<Payload, MigrationError> {
		Ok(registry.clone())
	}
	/// How stored history survives this step.
	fn history_policy(&self) -> HistoryPolicy {
		HistoryPolicy::Untouched
	}
	/// Transform one history record. Called only under [`HistoryPolicy::Rewrite`].
	fn migrate_delta(&self, delta: &Payload) -> Result<Payload, MigrationError> {
		Ok(delta.clone())
	}
	/// Transform one op of the hot log, which outlives a reopen until it retires.
	fn migrate_hot_op(&self, hot_op: &Payload) -> Result<Payload, MigrationError> {
		Ok(hot_op.clone())
	}
	/// Transform the per-peer session payload.
	fn migrate_session(&self, session: &Payload) -> Result<Payload, MigrationError> {
		Ok(session.clone())
	}
}

/// Converts a frozen stored type to its counterpart in the next format version. `cargo run migration snapshot`
/// generates these for every type a version declares again, leaving the parts that changed to the author.
pub trait Upgrade {
	/// This type's counterpart in the next format version.
	type Next;
	/// Convert to the next format version.
	fn upgrade(self) -> Result<Self::Next, MigrationError>;
}
